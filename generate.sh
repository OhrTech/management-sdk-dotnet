#!/bin/sh
# Regenerates src/OhrTech.Management/Generated/OhrManagementClient.g.cs from openapi.json.
#   ./generate.sh                use the committed openapi.json
#   ./generate.sh <url|file>     update openapi.json first, e.g. from the spec repo:
#       ./generate.sh https://raw.githubusercontent.com/OhrTech/management-api/main/openapi.json
#     or from the running API: ./generate.sh https://api.ohrtech.net/v1/openapi.json
#     (review the diff: within v1 the API only ever adds)
set -eu
cd "$(dirname "$0")"
if [ $# -gt 0 ]; then
    case "$1" in
        http://*|https://*) curl -fsS "$1" > openapi.json.new ;;
        *) cp "$1" openapi.json.new ;;
    esac
    python3 -m json.tool --indent 2 openapi.json.new > openapi.json
    rm openapi.json.new
fi
dotnet tool restore >/dev/null
dotnet tool run nswag openapi2csclient \
    /input:openapi.json \
    /output:src/OhrTech.Management/Generated/OhrManagementClient.g.cs \
    /namespace:OhrTech.Management \
    /className:OhrManagementClient \
    /operationGenerationMode:SingleClientFromOperationId \
    /generateClientInterfaces:true \
    /injectHttpClient:true \
    /useBaseUrl:false \
    /jsonLibrary:SystemTextJson \
    /generateNullableReferenceTypes:true \
    /generateOptionalPropertiesAsNullable:true \
    /generateDataAnnotations:false \
    /classStyle:Poco \
    /anyType:System.Text.Json.Nodes.JsonNode \
    /dateTimeType:System.DateTimeOffset \
    /arrayType:System.Collections.Generic.List \
    /arrayInstanceType:System.Collections.Generic.List \
    /dictionaryType:System.Collections.Generic.Dictionary \
    /dictionaryInstanceType:System.Collections.Generic.Dictionary \
    /responseArrayType:System.Collections.Generic.List \
    /responseDictionaryType:System.Collections.Generic.Dictionary \
    /exceptionClass:OhrApiException \
    /generateOptionalParameters:true \
    /parameterArrayType:System.Collections.Generic.IEnumerable

# Serialize through the source-generated metadata (Json.cs), never reflection: the generated calls
# that take JsonSerializerOptions are flagged by the trim and AOT analyzers in every app that
# publishes trimmed or native AOT, even though the options' resolver is the generated context.
python3 - <<'PY'
p = "src/OhrTech.Management/Generated/OhrManagementClient.g.cs"
s = open(p).read()
edits = [
    ("System.Text.Json.JsonSerializer.SerializeToUtf8Bytes(body, JsonSerializerSettings)", "SerializeBody(body)", 1),
    ("System.Text.Json.JsonSerializer.Deserialize<T>(responseText, JsonSerializerSettings)",
     "System.Text.Json.JsonSerializer.Deserialize(responseText, TypeInfo<T>())", 1),
    ("System.Text.Json.JsonSerializer.DeserializeAsync<T>(responseStream, JsonSerializerSettings, cancellationToken)",
     "System.Text.Json.JsonSerializer.DeserializeAsync(responseStream, TypeInfo<T>(), cancellationToken)", 1),
    # A string response is text (a PEM, a JWS), not a JSON string.
    ("var objectResponse_ = await ReadObjectResponseAsync<string>(response_, headers_, cancellationToken).ConfigureAwait(false);",
     "var objectResponse_ = new ObjectResponseResult<string>(await ReadAsStringAsync(response_.Content, cancellationToken).ConfigureAwait(false), string.Empty);", 1),
    ("        private string ConvertToString(object? value, System.Globalization.CultureInfo cultureInfo)",
     "#if NET5_0_OR_GREATER\n"
     "        [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2075\", Justification = \"No operation takes an enum parameter.\")]\n"
     "#endif\n"
     "        private string ConvertToString(object? value, System.Globalization.CultureInfo cultureInfo)", 1),
]
for old, new, minimum in edits:
    n = s.count(old)
    if n < minimum:
        raise SystemExit(f"generate.sh: expected generated code not found: {old}")
    s = s.replace(old, new)
open(p, "w").write(s)
PY

# Source-generated JSON metadata for every type the client sends or receives, so the client works
# where reflection-based serialization is off: .NET 10 file-based apps (dotnet run app.cs),
# trimmed and native AOT apps.
python3 - <<'PY'
import re
src = open("src/OhrTech.Management/Generated/OhrManagementClient.g.cs").read()
classes = sorted(set(re.findall(r"^    public partial class (\w+)\b(?!<)", src, re.M)) - {"OhrManagementClient", "OhrApiException"})
enums = sorted(set(re.findall(r"^    public enum (\w+)", src, re.M)))
lists = sorted(set(re.findall(r"Task<System\.Collections\.Generic\.List<(\w+)>>", src)))
lines = [
    "//----------------------",
    "// <auto-generated>",
    "//     Written by generate.sh from OhrManagementClient.g.cs. Do not edit.",
    "// </auto-generated>",
    "//----------------------",
    "",
    "namespace OhrTech.Management",
    "{",
    "    /// <summary>Source-generated JSON metadata for every API type: use it to serialize them in trimmed and native AOT apps.</summary>",
    "    [System.Text.Json.Serialization.JsonSourceGenerationOptions]",
]
lines += [f"    [System.Text.Json.Serialization.JsonSerializable(typeof({t}))]" for t in classes + enums]
lines += [f"    [System.Text.Json.Serialization.JsonSerializable(typeof(System.Collections.Generic.List<{t}>))]" for t in lists]
lines += [
    "    public partial class OhrManagementJsonContext : System.Text.Json.Serialization.JsonSerializerContext",
    "    {",
    "    }",
    "}",
    "",
]
open("src/OhrTech.Management/Generated/OhrManagementJsonContext.g.cs", "w").write("\n".join(lines))
print(f"JSON context: {len(classes)} classes, {len(enums)} enums, {len(lists)} lists")
PY

